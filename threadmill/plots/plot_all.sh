#!/usr/bin/env bash
# Generates the gnuplot scripts from whatever is in results/ and runs them.
#
# The .gp files are generated rather than hand-written for one reason: the
# number of repetitions is configurable, so the speedup column is not at a fixed
# index. This script first reduces each CSV to a three-column "threads avg
# speedup" data file with awk, after which every plot is trivially portable.
#
#   plots/plot_all.sh                 reads results/, writes plots/*.png
#   RESULTS=other plots/plot_all.sh   read a different results directory
set -euo pipefail

cd "$(dirname "$0")/.."
RESULTS=${RESULTS:-results}
PLOTS=plots
DATA=$PLOTS/data

command -v gnuplot >/dev/null || {
    echo "gnuplot not found. Install it (apt install gnuplot / brew install gnuplot)." >&2
    echo "The .gp scripts will still be generated so they can be run elsewhere." >&2
}

mkdir -p "$DATA"

# CSV -> "threads avg speedup", using NF so the repetition count does not matter.
for csv in "$RESULTS"/*.csv; do
    [[ -e "$csv" ]] || { echo "no CSVs in $RESULTS/" >&2; exit 1; }
    awk -F, 'NR>1 && NF>=3 {print $1, $(NF-1), $NF}' "$csv" \
        > "$DATA/$(basename "${csv%.csv}").dat"
done

# emit_plot <basename> <title> <ylabel> <mode:speedup|runtime> <file:label>...
emit_plot() {
    local base=$1 title=$2 ylabel=$3 mode=$4; shift 4
    local gp="$PLOTS/$base.gp" col=3 extra=""
    [[ $mode == runtime ]] && { col=2; extra='set logscale y'; }

    {
        echo "# generated by plots/plot_all.sh -- regenerate, do not hand-edit"
        echo "set terminal pngcairo size 1000,680 enhanced font 'Helvetica,12'"
        echo "set output '$PLOTS/$base.png'"
        echo "set title \"$title\""
        echo "set xlabel 'Number of OpenMP threads'"
        echo "set ylabel '$ylabel'"
        echo "set key outside right top"
        echo "set grid"
        echo "set xtics (1,2,4,6,8,10,12,14,16)"
        [[ -n $extra ]] && echo "$extra"
        printf 'plot '
        local sep="" spec f label
        for spec in "$@"; do
            f=${spec%%:*}; label=${spec#*:}
            printf "%s'%s' using 1:%d with linespoints lw 2 pt 7 title '%s'" \
                   "$sep" "$DATA/$f.dat" "$col" "$label"
            # $'...' so the continuation is a real backslash-newline: printf does
            # not expand escapes inside %s arguments, only in the format string.
            sep=$', \\\n     '
        done
        # The y=x reference makes it obvious where scaling departs from linear.
        [[ $mode == speedup ]] && printf ", \\\\\n     x with lines lw 1 dt 2 lc rgb '#888888' title 'ideal (linear)'"
        printf '\n'
    } > "$gp"

    if command -v gnuplot >/dev/null; then
        gnuplot "$gp" && echo "wrote $PLOTS/$base.png"
    fi
}

have() { [[ -s "$DATA/$1.dat" ]]; }

# ---- problem 1: one figure per matrix order, OMM against every block size ----
for csv in "$RESULTS"/p1_omm_n*.csv; do
    [[ -e "$csv" ]] || continue
    n=$(basename "$csv" .csv); n=${n#p1_omm_n}
    series=("p1_omm_n$n:OMM (unblocked)")
    for b in 4 8 16 32 64; do
        have "p1_bmm_n${n}_b${b}" && series+=("p1_bmm_n${n}_b${b}:BMM block $b")
    done
    emit_plot "p1_speedup_n$n" "Problem 1: A^2 speedup, N = $n" "Speedup vs 1 thread" speedup "${series[@]}"
    emit_plot "p1_runtime_n$n" "Problem 1: A^2 runtime, N = $n" "Average runtime (s, log scale)" runtime "${series[@]}"
done

# ---- problem 2 ----
p2=()
for f in "$DATA"/p2_chain_n*.dat;    do [[ -e $f ]] && p2+=("$(basename "$f" .dat):addition chain + 3-mult complex"); done
for f in "$DATA"/p2_naive14_n*.dat;  do [[ -e $f ]] && p2+=("$(basename "$f" .dat):14 successive + 4-mult complex"); done
((${#p2[@]})) && {
    emit_plot p2_speedup "Problem 2: X^15 speedup" "Speedup vs 1 thread" speedup "${p2[@]}"
    emit_plot p2_runtime "Problem 2: X^15 runtime" "Average runtime (s, log scale)" runtime "${p2[@]}"
}

# ---- problem 3 ----
p3=()
for f in "$DATA"/p3_counting_n*.dat; do [[ -e $f ]] && p3+=("$(basename "$f" .dat):counting sort"); done
for f in "$DATA"/p3_merge_n*.dat;    do [[ -e $f ]] && p3+=("$(basename "$f" .dat):parallel merge sort"); done
((${#p3[@]})) && {
    emit_plot p3_speedup "Problem 3: sorting speedup" "Speedup vs 1 thread" speedup "${p3[@]}"
    emit_plot p3_runtime "Problem 3: sorting runtime" "Average runtime (s, log scale)" runtime "${p3[@]}"
}

# ---- problems 4 and 5 ----

# Print "2^k" when $1 is an exact power of two, else the number itself. The
# sieve range is a run-time parameter, so the plot must state which range it
# actually measured -- a title that just says "segmented sieve" lets a reader
# assume the full assigned range no matter what was run.
pow2() {
    local n=$1 k=0
    while (( n > 1 && n % 2 == 0 )); do n=$((n / 2)); k=$((k + 1)); done
    (( n == 1 )) && echo "2^$k" || echo "$1"
}

have p4_primes && {
    p4args=$(sed -n 's/^args=//p' "$RESULTS/p4_primes.meta")
    p4lo=$(sed -n 's/.*--low \([0-9]*\).*/\1/p' <<<"$p4args")
    p4hi=$(sed -n 's/.*--high \([0-9]*\).*/\1/p' <<<"$p4args")
    p4range="[$(pow2 "$p4lo"), $(pow2 "$p4hi"))"
    emit_plot p4_speedup "Problem 4: primes in $p4range -- speedup" "Speedup vs 1 thread" speedup "p4_primes:segmented sieve"
    emit_plot p4_runtime "Problem 4: primes in $p4range -- runtime" "Average runtime (s, log scale)" runtime "p4_primes:segmented sieve"
}
for f in "$DATA"/p5_dot_n*.dat; do
    [[ -e $f ]] || continue
    b=$(basename "$f" .dat)
    emit_plot p5_speedup "Problem 5: dot product speedup" "Speedup vs 1 thread" speedup "$b:OpenMP reduction"
    emit_plot p5_runtime "Problem 5: dot product runtime" "Average runtime (s, log scale)" runtime "$b:OpenMP reduction"
done

echo "gnuplot scripts in $PLOTS/*.gp, data in $DATA/"
